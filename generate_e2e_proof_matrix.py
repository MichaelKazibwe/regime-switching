    """
    Validate the proof matrix itself.

    This function is a fail-closed integrity gate around the audit
    artifact.

    It detects:

        - empty matrices;
        - malformed row objects;
        - duplicate proof IDs;
        - missing fields;
        - invalid statuses;
        - missing phases;
        - invalid proof ID format;
        - non-default initial status;
        - missing expected results.

    The matrix must pass this validation before it is written.
    """

    if not rows:
        raise RuntimeError(
            "E2E proof matrix is empty."
        )

    proof_ids: set[str] = set()

    for index, row in enumerate(
        rows,
        start=1,
    ):

        if not isinstance(
            row,
            ProofRow,
        ):
            raise TypeError(
                f"Proof row {index} is not a ProofRow."
            )

        # --------------------------------------------------------------
        # PROOF ID
        # --------------------------------------------------------------

        if not row.proof_id.strip():
            raise ValueError(
                f"Proof row {index} has an empty proof_id."
            )

        if row.proof_id in proof_ids:
            raise ValueError(
                f"Duplicate proof ID detected: "
                f"{row.proof_id}"
            )

        proof_ids.add(row.proof_id)

        if not row.proof_id.startswith(
            "E2E-"
        ):
            raise ValueError(
                f"Invalid proof ID: "
                f"{row.proof_id}"
            )

        # --------------------------------------------------------------
        # REQUIRED STRING FIELDS
        # --------------------------------------------------------------

        required_fields = (
            "phase",
            "boundary",
            "input_artifact",
            "output_artifact",
            "invariant",
            "test_action",
            "expected_result",
        )

        for field_name in required_fields:

            value = getattr(
                row,
                field_name,
            )

            if not isinstance(
                value,
                str,
            ):
                raise TypeError(
                    f"{row.proof_id}: "
                    f"{field_name} must be a string."
                )

            if not value.strip():
                raise ValueError(
                    f"{row.proof_id}: "
                    f"{field_name} cannot be empty."
                )

        # --------------------------------------------------------------
        # PHASE
        # --------------------------------------------------------------

        if row.phase not in REQUIRED_PHASES:
            raise ValueError(
                f"{row.proof_id}: invalid phase "
                f"{row.phase!r}."
            )

        # --------------------------------------------------------------
        # STATUS
        # --------------------------------------------------------------

        if row.status not in VALID_PROOF_STATUSES:
            raise ValueError(
                f"{row.proof_id}: invalid status "
                f"{row.status!r}."
            )

        # --------------------------------------------------------------
        # INITIAL MATRIX MUST BE UNEXECUTED
        # --------------------------------------------------------------

        if row.status != DEFAULT_PROOF_STATUS:
            raise ValueError(
                f"{row.proof_id}: generated matrix must "
                f"start as {DEFAULT_PROOF_STATUS}, got "
                f"{row.status!r}."
            )

    # ====================================================================
    # PHASE COVERAGE
    # ====================================================================

    actual_phases = {
        row.phase
        for row in rows
    }

    missing_phases = (
        set(REQUIRED_PHASES)
        - actual_phases
    )

    if missing_phases:
        raise RuntimeError(
            "Proof matrix is missing required phases: "
            + ", ".join(
                sorted(
                    missing_phases
                )
            )
        )

    # ====================================================================
    # PROOF COUNT
    # ====================================================================

    if len(rows) != 54:
        raise RuntimeError(
            "Unexpected proof matrix size: "
            f"expected 54 rows, got {len(rows)}."
        )

    print(
        f"[PASS] Proof matrix integrity validated: "
        f"{len(rows)} rows."
    )


