@dataclass
class ProofRow:
    """
    One auditable end-to-end proof requirement.

    Every row represents one independently observable invariant.

    The row is intentionally declarative. It does not execute the
    associated proof.
    """

    proof_id: str
    phase: str
    boundary: str
    input_artifact: str
    output_artifact: str
    invariant: str
    test_action: str
    expected_result: str
    status: str = DEFAULT_PROOF_STATUS
    evidence: str = ""
    notes: str = ""


# ========================================================================
# PROOF MATRIX BUILDER
# ========================================================================


class ProofMatrixBuilder:
    """
    Deterministic builder for the Phase 1 E2E proof matrix.

    The builder uses keyword arguments when constructing ProofRow
    objects. This deliberately prevents positional-field omissions such
    as the previous E2E-02 defect.
    """

    def __init__(self) -> None:

        self._rows: list[ProofRow] = []

    def add(
        self,
        *,
        proof_id: str,
        phase: str,
        boundary: str,
        input_artifact: str,
        output_artifact: str,
        invariant: str,
        test_action: str,
        expected_result: str,
        status: str = DEFAULT_PROOF_STATUS,
        evidence: str = "",
        notes: str = "",
    ) -> None:
        """
        Add one proof row using keyword-only arguments.

        Keyword-only construction is deliberate. It makes malformed
        positional calls impossible.
        """

        row = ProofRow(
            proof_id=proof_id,
            phase=phase,
            boundary=boundary,
            input_artifact=input_artifact,
            output_artifact=output_artifact,
            invariant=invariant,
            test_action=test_action,
            expected_result=expected_result,
            status=status,
            evidence=evidence,
            notes=notes,
        )

        self._rows.append(row)

    def rows(self) -> list[ProofRow]:
        """
        Return a copy of the matrix rows.
        """

        return list(self._rows)


