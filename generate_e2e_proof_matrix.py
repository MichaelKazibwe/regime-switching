# ========================================================================
# MAIN
# ========================================================================


def main() -> int:
    """
    Main program.

    Fail closed if the matrix itself is malformed.
    """

    print()
    print(
        "Generating E2E proof matrix..."
    )

    try:

        # --------------------------------------------------------------
        # DISCOVER PROJECT
        # --------------------------------------------------------------

        modules = discover_modules()

        git_state = get_git_status()

        git_summary = get_git_summary()

        # --------------------------------------------------------------
        # BUILD MATRIX
        # --------------------------------------------------------------

        rows = build_matrix()

        # --------------------------------------------------------------
        # VALIDATE MATRIX
        # --------------------------------------------------------------

        validate_matrix(
            rows
        )

        # --------------------------------------------------------------
        # GENERATE MARKDOWN
        # --------------------------------------------------------------

        markdown = generate_markdown(
            rows=rows,
            modules=modules,
            git_state=git_state,
            git_summary=git_summary,
        )

        # --------------------------------------------------------------
        # WRITE OUTPUTS
        # --------------------------------------------------------------

        MARKDOWN_OUTPUT.write_text(
            markdown,
            encoding="utf-8",
        )

        write_csv(
            rows
        )

        write_json(
            rows=rows,
            modules=modules,
            git_state=git_state,
            git_summary=git_summary,
        )

        # --------------------------------------------------------------
        # REPORT
        # --------------------------------------------------------------

        print_terminal_report(
            rows=rows,
            modules=modules,
            git_summary=git_summary,
        )

        return 0

    except Exception as exc:

        print()
        print("=" * 76)
        print(
            "E2E PROOF MATRIX GENERATION FAILED"
        )
        print("=" * 76)
        print()
        print(
            f"ERROR: {type(exc).__name__}: {exc}"
        )
        print()
        print(
            "FAIL-CLOSED: no valid proof matrix "
            "should be treated as generated."
        )
        print()
        print("=" * 76)

        return 1


