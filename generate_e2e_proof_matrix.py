# PROJECT MODULE DISCOVERY
# ========================================================================


def discover_modules() -> dict[str, bool]:
    """
    Discover required production modules.

    Missing modules are reported as missing.

    No imports are performed here.

    This avoids triggering module-level side effects while generating
    the inventory.
    """

    return {
        filename: (
            PROJECT_ROOT / filename
        ).is_file()
        for filename in REQUIRED_PRODUCTION_MODULES
    }


# ========================================================================
# GIT STATUS
# ========================================================================


def get_git_status() -> str:
    """
    Return read-only Git status.

    No Git state is modified.
    """

    try:

        result = subprocess.run(
            [
                "git",
                "status",
                "--short",
                "--branch",
            ],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            check=False,
        )

    except OSError as exc:

        return (
            "GIT_STATUS_UNAVAILABLE: "
            f"{exc}"
        )

    if result.returncode != 0:

        stderr = (
            result.stderr.strip()
            or "unknown Git error"
        )

        return (
            "GIT_STATUS_UNAVAILABLE: "
            f"{stderr}"
        )

    output = result.stdout.strip()

    return output or "CLEAN"


# ========================================================================
# GIT SUMMARY
# ========================================================================


def get_git_summary() -> dict[str, str]:
    """
    Collect a compact read-only Git summary.
    """

    summary: dict[str, str] = {}

    commands = {
        "branch": [
            "git",
            "branch",
            "--show-current",
        ],
        "head": [
            "git",
            "rev-parse",
            "--short",
            "HEAD",
        ],
        "upstream": [
            "git",
            "rev-parse",
            "--abbrev-ref",
            "--symbolic-full-name",
            "@{u}",
        ],
    }

    for key, command in commands.items():

        try:

            result = subprocess.run(
                command,
                cwd=PROJECT_ROOT,
                capture_output=True,
                text=True,
                check=False,
            )

        except OSError:

            summary[key] = "UNAVAILABLE"

            continue

        if result.returncode != 0:

            summary[key] = "UNAVAILABLE"

        else:

            summary[key] = (
                result.stdout.strip()
                or "UNAVAILABLE"
            )

    return summary


