def status_symbol(
    status: str,
) -> str:
    """
    Convert proof status to a human-readable symbol.
    """

    symbols = {
        "PASS": "🟢",
        "FAIL": "🔴",
        "BLOCKED": "🟠",
        "NOT_EXECUTED": "⚪",
        "SKIPPED": "⚫",
    }

    return symbols.get(
        status,
        "⚪",
    )


def markdown_escape(
    value: str,
) -> str:
    """
    Escape basic Markdown table delimiters.
    """

    return (
        value
        .replace("|", "\\|")
        .replace("\n", " ")
        .replace("\r", " ")
    )


