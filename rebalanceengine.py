"""
===============================================================
REBALANCE ENGINE

Institutional Portfolio Rebalancing Engine

Converts target allocations into orders for the authorized
execution pipeline.

IMPORTANT EXECUTION BOUNDARY
----------------------------
RebalanceEngine is a planning component.

It may:
    - calculate portfolio value;
    - generate canonical orders;
    - estimate transaction costs;
    - produce a rebalance preview/report.

It must NOT:
    - execute orders directly;
    - call ExecutionEngine.execute();
    - submit orders to an OMS;
    - route orders to a broker;
    - submit orders to a broker;
    - mutate portfolio state through execution.

Orders generated by this component must pass through the
authorized execution pipeline before execution.

===============================================================
"""

from __future__ import annotations

from basecomponent import BaseObject

from order import Order
from portfolioaccount import PortfolioAccount
from transactioncostmodel import TransactionCostModel


# ============================================================
# REBALANCE ENGINE
# ============================================================


class RebalanceEngine(BaseObject):
    """
    Institutional portfolio rebalancing planner.

    The RebalanceEngine converts target portfolio allocations
    into canonical Order objects and estimates the associated
    transaction costs.

    Direct execution is intentionally prohibited.

    Execution must occur through the authorized execution
    architecture:

        ExecutionAuthorization
                ↓
        AuthorizedOrderIntent
                ↓
        OMS
                ↓
        AuthorizedRoutingHandoff
                ↓
        BrokerRouter
                ↓
        AuthorizedExecutionHandoff
                ↓
        BrokerExecutionEngine
                ↓
        ExecutionEngine

    This component therefore remains upstream of execution.
    """

    API_VERSION = "1.0.0"

    PUBLIC_METHODS = (
        "generate_orders",
        "estimate_cost",
        "rebalance",
        "summary",
        "metadata",
        "health_check",
    )

    DIRECT_EXECUTION_ERROR = (
        "Direct RebalanceEngine execution is disabled. "
        "Orders must pass through the authorized execution pipeline."
    )

    # ========================================================
    # CONSTRUCTOR
    # ========================================================

    def __init__(
        self,
        transaction_cost_model: TransactionCostModel | None = None,
    ) -> None:
        """
        Construct the RebalanceEngine.

        The engine deliberately has no ExecutionEngine dependency.

        This is an explicit Phase IV-I-J execution-boundary
        invariant: RebalanceEngine may generate orders but may
        not execute them.
        """

        super().__init__()

        self.transaction_cost_model = (
            transaction_cost_model
            if transaction_cost_model is not None
            else TransactionCostModel()
        )

        # ----------------------------------------------------
        # Cached planning state
        # ----------------------------------------------------

        self.last_orders: list[Order] = []

        self.last_trades: list = []

        self.last_report: dict = {}

    # ========================================================
    # GENERATE ORDERS
    # ========================================================

    def generate_orders(
        self,
        account: PortfolioAccount,
        target_weights: dict[str, float],
        prices: dict[str, float],
    ) -> list[Order]:
        """
        Generate canonical orders required to rebalance the
        portfolio to the supplied target weights.

        This method performs planning only.

        It does NOT:
            - authorize orders;
            - submit orders;
            - route orders;
            - execute orders;
            - mutate portfolio state.

        Parameters
        ----------
        account:
            Portfolio account containing current cash and
            positions.

        target_weights:
            Target portfolio allocation by ticker.

        prices:
            Current execution-price assumptions by ticker.

        Returns
        -------
        list[Order]
            Canonical orders representing the required rebalance.
        """

        # ----------------------------------------------------
        # PORTFOLIO VALUE
        # ----------------------------------------------------

        portfolio_value = account.cash

        for position in account.positions.values():
            portfolio_value += (
                position.shares
                * prices[position.ticker]
            )

        # ----------------------------------------------------
        # ORDER GENERATION
        # ----------------------------------------------------

        orders: list[Order] = []

        for ticker, target_weight in target_weights.items():

            price = prices[ticker]

            target_value = (
                portfolio_value
                * target_weight
            )

            target_shares = (
                target_value
                / price
            )

            current_position = account.positions.get(
                ticker
            )

            current_shares = (
                0.0
                if current_position is None
                else current_position.shares
            )

            difference = (
                target_shares
                - current_shares
            )

            # ------------------------------------------------
            # No meaningful trade required
            # ------------------------------------------------

            if abs(difference) < 1e-8:
                continue

            # ------------------------------------------------
            # Determine order side
            # ------------------------------------------------

            side = (
                "BUY"
                if difference > 0
                else "SELL"
            )

            # ------------------------------------------------
            # Construct canonical Order
            # ------------------------------------------------

            orders.append(
                Order(
                    order_id=(
                        f"ORD-REBAL-{len(orders) + 1:06d}"
                    ),
                    ticker=ticker,
                    side=side,
                    quantity=abs(difference),
                )
            )

        # ----------------------------------------------------
        # CACHE
        # ----------------------------------------------------

        self.last_orders = orders

        return orders

    # ========================================================
    # ESTIMATE COST
    # ========================================================

    def estimate_cost(
        self,
        orders: list[Order],
        prices: dict[str, float],
    ) -> dict:
        """
        Estimate transaction costs for a list of orders.

        This method is purely analytical and has no execution
        side effects.
        """

        total_commission = 0.0

        total_slippage = 0.0

        total_trade_value = 0.0

        for order in orders:

            execution_price = prices[
                order.ticker
            ]

            trade_value = (
                order.quantity
                * execution_price
            )

            commission, slippage = (
                self.transaction_cost_model.estimate(
                    shares=order.quantity,
                    price=execution_price,
                )
            )

            total_trade_value += trade_value

            total_commission += commission

            total_slippage += slippage

        # ----------------------------------------------------
        # AVERAGE COST
        # ----------------------------------------------------

        average_cost_per_order = (
            0.0
            if not orders
            else (
                total_commission
                + total_slippage
            )
            / len(orders)
        )

        # ----------------------------------------------------
        # REPORT
        # ----------------------------------------------------

        report = {
            "orders": len(orders),
            "trade_value": total_trade_value,
            "commission": total_commission,
            "slippage": total_slippage,
            "total_cost": (
                total_commission
                + total_slippage
            ),
            "average_cost_per_order": (
                average_cost_per_order
            ),
        }

        return report

    # ========================================================
    # REBALANCE
    # ========================================================

    def rebalance(
        self,
        account: PortfolioAccount,
        target_weights: dict[str, float],
        prices: dict[str, float],
        execute: bool = False,
    ) -> dict:
        """
        Generate a rebalance plan.

        The default is explicitly non-executing.

        Direct execution through this component is prohibited.
        Passing execute=True therefore fails closed rather than
        silently changing the caller's requested behavior.

        The planning path:

            account
                ↓
            generate_orders()
                ↓
            estimate_cost()
                ↓
            preview/report

        The execution path is deliberately outside this class.

        Parameters
        ----------
        account:
            Portfolio account to analyse.

        target_weights:
            Desired portfolio weights.

        prices:
            Price assumptions used for order generation and
            transaction-cost estimation.

        execute:
            Must remain False.

            True raises RuntimeError.

        Returns
        -------
        dict
            Rebalance planning report.

        Raises
        ------
        RuntimeError
            If direct execution is requested.
        """

        # ====================================================
        # EXECUTION BOUNDARY
        # ====================================================

        if execute:
            raise RuntimeError(
                self.DIRECT_EXECUTION_ERROR
            )

        # ====================================================
        # GENERATE ORDERS
        # ====================================================

        orders = self.generate_orders(
            account,
            target_weights,
            prices,
        )

        # ====================================================
        # ESTIMATE COST
        # ====================================================

        estimated_cost = self.estimate_cost(
            orders,
            prices,
        )

        # ====================================================
        # NO DIRECT EXECUTION
        # ====================================================

        trades: list = []

        # ====================================================
        # CACHE
        # ====================================================

        self.last_orders = orders

        self.last_trades = trades

        # ====================================================
        # REPORT
        # ====================================================

        report = {
            "orders": [
                order.to_dict()
                for order in orders
            ],
            "trades": [],
            "estimated_cost": estimated_cost,
            "cash_after": account.cash,
            "positions": len(
                account.positions
            ),
            "executions": 0,
            "preview_only": True,
            "execution_blocked": True,
            "execution_boundary": (
                "authorized_execution_pipeline"
            ),
        }

        self.last_report = report

        return report

    # ========================================================
    # SUMMARY
    # ========================================================

    def summary(
        self,
    ) -> dict:
        """
        Return a summary of the most recent rebalance plan.
        """

        return {
            "orders": len(
                self.last_orders
            ),
            "trades": len(
                self.last_trades
            ),
            "cash": self.last_report.get(
                "cash_after",
                0.0,
            ),
            "estimated_cost": (
                self.last_report.get(
                    "estimated_cost",
                    {},
                ).get(
                    "total_cost",
                    0.0,
                )
            ),
            "preview_only": self.last_report.get(
                "preview_only",
                True,
            ),
            "execution_blocked": self.last_report.get(
                "execution_blocked",
                True,
            ),
        }

    # ========================================================
    # METADATA
    # ========================================================

    @property
    def metadata(
        self,
    ) -> dict:
        """
        Return component metadata and current planning state.
        """

        metadata = super().metadata

        metadata.update(
            self.summary()
        )

        return metadata

    # ========================================================
    # HEALTH CHECK
    # ========================================================

    def health_check(
        self,
    ) -> bool:
        """
        Verify that the planning dependencies are available.

        ExecutionEngine is intentionally absent from this check
        because RebalanceEngine no longer depends on it.
        """

        return (
            self.transaction_cost_model is not None
        )


# ============================================================
# REGRESSION TEST
# ============================================================

def test_rebalance_engine() -> None:
    """
    Regression test for the planning-only RebalanceEngine.

    This test explicitly verifies that:

        1. orders are generated;
        2. transaction costs are estimated;
        3. no trades are produced;
        4. account cash is not mutated;
        5. direct execution is blocked;
        6. the public contract remains stable.
    """

    from portfolioaccount import PortfolioAccount

    # --------------------------------------------------------
    # ACCOUNT
    # --------------------------------------------------------

    account = PortfolioAccount(
        initial_cash=100000.0
    )

    initial_cash = account.cash

    # --------------------------------------------------------
    # ENGINE
    # --------------------------------------------------------

    engine = RebalanceEngine()

    target_weights = {
        "SPY": 0.60,
        "QQQ": 0.40,
    }

    prices = {
        "SPY": 500.0,
        "QQQ": 400.0,
    }

    # --------------------------------------------------------
    # PLANNING PATH
    # --------------------------------------------------------

    report = engine.rebalance(
        account,
        target_weights,
        prices,
    )

    # --------------------------------------------------------
    # ORDERS
    # --------------------------------------------------------

    assert len(
        report["orders"]
    ) == 2

    # --------------------------------------------------------
    # NO EXECUTION
    # --------------------------------------------------------

    assert len(
        report["trades"]
    ) == 0

    assert report["executions"] == 0

    assert (
        report["preview_only"]
        is True
    )

    assert (
        report["execution_blocked"]
        is True
    )

    assert (
        report["execution_boundary"]
        == "authorized_execution_pipeline"
    )

    # --------------------------------------------------------
    # ACCOUNT MUST NOT BE MUTATED
    # --------------------------------------------------------

    assert (
        report["cash_after"]
        == initial_cash
    )

    assert (
        account.cash
        == initial_cash
    )

    # --------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------

    summary = engine.summary()

    assert summary["orders"] == 2

    assert summary["trades"] == 0

    assert (
        summary["cash"]
        == initial_cash
    )

    assert summary["preview_only"] is True

    assert summary["execution_blocked"] is True

    # --------------------------------------------------------
    # HEALTH
    # --------------------------------------------------------

    assert engine.health_check()

    # --------------------------------------------------------
    # METADATA
    # --------------------------------------------------------

    metadata = engine.metadata

    assert metadata["orders"] == 2

    assert metadata["trades"] == 0

    assert metadata["preview_only"] is True

    assert metadata["execution_blocked"] is True

    # --------------------------------------------------------
    # API CONTRACT
    # --------------------------------------------------------

    assert RebalanceEngine.API_VERSION == "1.0.0"

    assert tuple(
        RebalanceEngine.PUBLIC_METHODS
    ) == (
        "generate_orders",
        "estimate_cost",
        "rebalance",
        "summary",
        "metadata",
        "health_check",
    )

    # --------------------------------------------------------
    # DIRECT EXECUTION MUST FAIL CLOSED
    # --------------------------------------------------------

    try:
        engine.rebalance(
            account,
            target_weights,
            prices,
            execute=True,
        )

    except RuntimeError as exc:

        assert (
            str(exc)
            == RebalanceEngine.DIRECT_EXECUTION_ERROR
        )

    else:

        raise AssertionError(
            "RebalanceEngine must reject direct execution."
        )

    # --------------------------------------------------------
    # ACCOUNT MUST STILL BE UNCHANGED
    # --------------------------------------------------------

    assert (
        account.cash
        == initial_cash
    )

    print(
        "RebalanceEngine tests passed."
    )


# ============================================================
# MAIN
# ============================================================

if __name__ == "__main__":
    test_rebalance_engine()