class _TestRegimeModel:
    """Deterministic regime model for regression testing."""

    def classify(
        self,
        **kwargs: Any,
    ) -> str:
        return "EXPANSION"


class _TestExpectedReturnForecaster:
    """Deterministic expected-return model."""

    def forecast(
        self,
        tickers: list[str],
        **kwargs: Any,
    ) -> dict[str, float]:
        return {
            ticker: 0.05
            for ticker in tickers
        }


class _TestCovarianceEngine:
    """Deterministic covariance model."""

    def estimate(
        self,
        tickers: list[str],
        **kwargs: Any,
    ) -> np.ndarray:
        return (
            np.eye(
                len(tickers),
                dtype=float,
            )
            * 0.04
        )


class _TestRegimeCovariance:
    """Deterministic regime-dependent covariance model."""

    def __init__(
        self,
    ) -> None:
        self.fitted = False

        self.last_regimes: Any = None

    def fit(
        self,
        returns: Any,
        regimes: Any,
    ) -> "_TestRegimeCovariance":
        self.fitted = True

        self.last_regimes = regimes

        return self

    def estimate(
        self,
        regime: str,
        **kwargs: Any,
    ) -> np.ndarray:
        if not self.fitted:
            raise RuntimeError(
                "fit() must be called before estimate()."
            )

        if regime != "EXPANSION":
            raise ValueError(
                "Unexpected test regime."
            )

        return (
            np.eye(
                2,
                dtype=float,
            )
            * 0.04
        )


class _TestOptimizer:
    """Deterministic equal-weight optimizer."""

    def optimize(
        self,
        tickers: list[str],
        **kwargs: Any,
    ) -> dict[str, float]:
        if not tickers:
            return {}

        weight = (
            1.0
            / len(tickers)
        )

        return {
            ticker: weight
            for ticker in tickers
        }


class _TestConstraints:
    """Deterministic pass-through constraints."""

    @staticmethod
    def enforce(
        weights: dict[str, float],
        **kwargs: Any,
    ) -> dict[str, float]:
        return dict(
            weights
        )


class _TestRiskModel:
    """Deterministic component-risk model."""

    def risk_contributions(
        self,
        weights: dict[str, float],
        covariance: np.ndarray,
        **kwargs: Any,
    ) -> dict[str, float]:
        tickers = list(
            weights
        )

        vector = np.asarray(
            [
                float(
                    weights[
                        ticker
                    ]
                )
                for ticker in tickers
            ],
            dtype=float,
        )

        marginal = (
            covariance
            @ vector
        )

        return {
            ticker: float(
                vector[index]
                * marginal[index]
            )
            for index, ticker in enumerate(
                tickers
            )
        }


class _TestScenarioEngine:
    """Deterministic scenario engine."""

    def compare(
        self,
        weights: dict[str, float],
        scenarios: Any,
        **kwargs: Any,
    ) -> dict[str, Any]:
        count = (
            len(
                scenarios
            )
            if hasattr(
                scenarios,
                "__len__",
            )
            else 1
        )

        return {
            "scenario_count": count,
            "status": "COMPLETED",
        }


