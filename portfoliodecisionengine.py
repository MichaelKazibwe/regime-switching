class DecisionSeverity(str, Enum):
    """Severity levels for decision-engine audit events."""
    INFO = 'INFO'
    WARNING = 'WARNING'
    ERROR = 'ERROR'

class PortfolioDecisionStatus(str, Enum):
    """Lifecycle status of a portfolio decision."""
    APPROVED = 'APPROVED'
    REJECTED = 'REJECTED'
    FAILED = 'FAILED'

@dataclass(frozen=True)
class DecisionEvent:
    """Immutable audit event generated by the decision engine."""
    timestamp: str
    event: str
    severity: str = DecisionSeverity.INFO.value
    message: str = ''
    component: Optional[str] = None
    data: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        """Serialize the audit event."""
        return asdict(self)

