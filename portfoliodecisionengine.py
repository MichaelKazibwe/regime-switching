    # RESTORE
    # ==================================================================

    @classmethod
    def from_dict(
        cls,
        data: dict[str, Any],
        **dependencies: Any,
    ) -> "PortfolioDecisionEngine":
        """Restore engine state from serialized data."""

        engine = cls(
            normalize_weights=bool(
                data.get(
                    "normalize_weights",
                    True,
                )
            ),
            weight_tolerance=float(
                data.get(
                    "weight_tolerance",
                    1e-8,
                )
            ),
            minimum_weight=float(
                data.get(
                    "minimum_weight",
                    0.0,
                )
            ),
            maximum_weight=float(
                data.get(
                    "maximum_weight",
                    1.0,
                )
            ),
            **dependencies,
        )

        engine._sequence = int(
            data.get(
                "sequence",
                0,
            )
        )

        engine._healthy = bool(
            data.get(
                "healthy",
                True,
            )
        )

        engine._decisions = []

        for item in data.get(
            "decisions",
            [],
        ):
            try:
                engine._decisions.append(
                    PortfolioDecision.from_dict(
                        item
                    )
                )
            except (
                TypeError,
                ValueError,
                AttributeError,
            ):
                continue

        engine.last_decision = (
            engine._decisions[-1]
            if engine._decisions
            else None
        )

        engine.decision_count = int(
            data.get(
                "decision_count",
                len(
                    engine._decisions
                ),
            )
        )

        engine.approved_count = int(
            data.get(
                "approved_count",
                sum(
                    decision.approved
                    for decision in engine._decisions
                ),
            )
        )

        engine.rejected_count = int(
            data.get(
                "rejected_count",
                sum(
                    decision.status
                    == PortfolioDecisionStatus.REJECTED.value
                    for decision in engine._decisions
                ),
            )
        )

        engine.failed_count = int(
            data.get(
                "failed_count",
                sum(
                    decision.status
                    == PortfolioDecisionStatus.FAILED.value
                    for decision in engine._decisions
                ),
            )
        )

        engine.audit_history = []

        for raw_event in data.get(
            "audit_history",
            [],
        ):
            try:
                engine.audit_history.append(
                    DecisionEvent(
                        timestamp=str(
                            raw_event.get(
                                "timestamp",
                                "",
                            )
                        ),
                        event=str(
                            raw_event.get(
                                "event",
                                "",
                            )
                        ),
                        severity=str(
                            raw_event.get(
                                "severity",
                                DecisionSeverity.INFO.value,
                            )
                        ),
                        message=str(
                            raw_event.get(
                                "message",
                                "",
                            )
                        ),
                        component=raw_event.get(
                            "component"
                        ),
                        data=dict(
                            raw_event.get(
                                "data",
                                {},
                            )
                        ),
                    )
                )
            except (
                TypeError,
                ValueError,
            ):
                continue

        return engine

