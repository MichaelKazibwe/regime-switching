    # ==================================================================
    # HEALTH CHECK
    # ==================================================================

    def health_check(
        self,
    ) -> dict[str, Any]:
        """
        Return component health information.

        Optional components do not cause overall health failure when
        unavailable. Core decision components are required only when
        they are necessary for a fully model-driven deployment.

        The deterministic fallback paths remain available for regression
        testing and controlled development environments.
        """

        components = {
            "asset_universe": (
                self.asset_universe
            ),
            "regime_model": (
                self.regime_model
            ),
            "expected_return_forecaster": (
                self.expected_return_forecaster
            ),
            "covariance_engine": (
                self.covariance_engine
            ),
            "regime_covariance": (
                self.regime_covariance
            ),
            "ensemble_covariance": (
                self.ensemble_covariance
            ),
            "black_litterman": (
                self.black_litterman
            ),
            "optimizer": (
                self.optimizer
            ),
            "constraints": (
                self.constraints
            ),
            "risk_model": (
                self.risk_model
            ),
            "risk_contribution_analyzer": (
                self.risk_contribution_analyzer
            ),
            "scenario_engine": (
                self.scenario_engine
            ),
        }

        required = {
            "regime_model",
            "expected_return_forecaster",
            "covariance_engine",
            "optimizer",
            "risk_model",
        }

        component_health: dict[
            str,
            Any,
        ] = {}

        overall = bool(
            self._healthy
        )

        for name, component in (
            components.items()
        ):
            if component is None:
                component_health[
                    name
                ] = {
                    "available": False,
                    "healthy": (
                        name not in required
                    ),
                    "optional": (
                        name not in required
                    ),
                }

                if name in required:
                    overall = False

                continue

            health_method = getattr(
                component,
                "health_check",
                None,
            )

            if callable(
                health_method
            ):
                try:
                    result = (
                        health_method()
                    )

                    component_health[
                        name
                    ] = (
                        result
                        if isinstance(
                            result,
                            dict,
                        )
                        else {
                            "available": True,
                            "healthy": (
                                result is not False
                            ),
                        }
                    )

                    if isinstance(
                        result,
                        dict,
                    ):
                        healthy = result.get(
                            "healthy",
                            True,
                        )

                        if (
                            healthy is False
                            and name in required
                        ):
                            overall = False

                    elif result is False:
                        if name in required:
                            overall = False

                except Exception as exc:
                    component_health[
                        name
                    ] = {
                        "available": True,
                        "healthy": False,
                        "error": str(
                            exc
                        ),
                    }

                    if name in required:
                        overall = False

                continue

            component_health[
                name
            ] = {
                "available": True,
                "healthy": True,
                "class": (
                    component.__class__.__name__
                ),
            }

        return {
            "api_version": self.API_VERSION,
            "healthy": overall,
            "component_count": len(
                components
            ),
            "components": component_health,
        }

